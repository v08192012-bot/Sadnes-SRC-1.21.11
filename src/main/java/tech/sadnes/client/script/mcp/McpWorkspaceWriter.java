package tech.sadnes.client.script.mcp;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Optional;
import net.minecraft.client.MinecraftClient;
import net.minecraft.resource.Resource;
import net.minecraft.util.Identifier;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import tech.sadnes.client.ClientInfo;
import tech.sadnes.client.script.editor.ScriptApiDocs;

final class McpWorkspaceWriter {
    private static final Logger LOGGER = LoggerFactory.getLogger("sadnes/MCP");
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().create();
    private static final String AUTO_GENERATED_MARKER = "<!-- auto-generated by sadnes client; edits will be overwritten on MCP start -->";

    private McpWorkspaceWriter() {
    }

    static void writeWorkspaceFiles(Path path, String string) {
        try {
            writeMcpConfig(path.resolve(".mcp.json"), string);
            String string2 = "<!-- auto-generated by sadnes client; edits will be overwritten on MCP start -->\n\n" + renderDoc("scripts/ai/guide.md", string);
            writeGeneratedFile(path.resolve("AGENTS.md"), string2);
            writeGeneratedFile(path.resolve("CLAUDE.md"), string2);
            writeGeneratedFile(
                path.resolve("API.md"),
                "<!-- auto-generated by sadnes client; edits will be overwritten on MCP start -->\n\n" + renderDoc("scripts/ai/api.md", string)
            );
        } catch (Exception exception) {
            LOGGER.warn("Failed to write MCP workspace files: {}", exception.toString());
        }
    }

    private static void writeMcpConfig(Path path, String string) throws IOException {
        JsonObject jsonObject = new JsonObject();
        if (Files.isRegularFile(path)) {
            try {
                jsonObject = JsonParser.parseString(Files.readString(path)).getAsJsonObject();
            } catch (Exception exception) {
            }
        }

        JsonObject jsonObject2 = jsonObject.has("mcpServers") && jsonObject.get("mcpServers").isJsonObject() ? jsonObject.getAsJsonObject("mcpServers") : new JsonObject();
        JsonObject jsonObject3 = new JsonObject();
        jsonObject3.addProperty("type", "http");
        jsonObject3.addProperty("url", string);
        jsonObject2.add("sadnes", jsonObject3);
        jsonObject.add("mcpServers", jsonObject2);
        Files.writeString(path, GSON.toJson(jsonObject));
    }

    private static void writeGeneratedFile(Path path, String string) throws IOException {
        if (Files.isRegularFile(path)) {
            String string2 = Files.readString(path);
            if (!string2.startsWith("<!-- auto-generated by sadnes client; edits will be overwritten on MCP start -->")) {
                return;
            }
        }

        Files.writeString(path, string);
    }

    private static String renderDoc(String string, String string2) {
        return readDocResource(string).replace("%URL%", string2).replace("%EVENTS%", buildEventsDoc()).replace("%API%", ScriptApiDocs.buildApiDoc());
    }

    private static String readDocResource(String string) {
        try {
            Optional optional = MinecraftClient.getInstance().getResourceManager().getResource(Identifier.of(ClientInfo.MOD_ID, string));
            if (optional.isPresent()) {
                try (InputStream inputStream = ((Resource)optional.get()).getInputStream()) {
                    return new String(inputStream.readAllBytes(), StandardCharsets.UTF_8);
                }
            }
        } catch (Exception exception) {
            LOGGER.warn("Failed to read doc resource {}: {}", string, exception.toString());
        }

        return "# sadnes scripts\n\nMCP server: %URL%\n\n## Events\n\n%EVENTS%\n\n## API\n\n%API%\n";
    }

    private static String buildEventsDoc() {
        return ScriptApiDocs.buildEventsDoc();
    }

    static String buildApiDoc() {
        return renderDoc("scripts/ai/api.md", "");
    }
}
